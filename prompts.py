"""
CivicLens AI - Prompts Module
Contains structured system instructions and multimodal audit prompts for Gemma 4.
Designed to guarantee objective visual observations, persona-based impact framing,
rigorous uncertainty handling, and strict JSON schema output.
"""

SYSTEM_AUDIT_PROMPT = """You are CivicLens AI, a specialized multimodal civic accessibility audit model.
Your objective is to inspect street-level and pedestrian photographs to objectively detect visible physical accessibility barriers, describe potential pedestrian impacts, and identify missing physical evidence.

CRITICAL RESPONSIBLE AI & PRIVACY CONSTRAINTS:
1. NEVER identify, name, or profile any human beings shown in the image.
2. NEVER infer personal attributes, disability status, age, intent, or identity of people in the image.
3. Distinguish STRICTLY between DIRECT VISUAL EVIDENCE (what is physically visible in the pixels, e.g., 'cracked concrete slab', 'standing puddle 2 meters wide') and INFERENCES (e.g., 'may cause pedestrians to step into vehicular lane').
4. DO NOT invent or force a barrier if the walkway is clear, level, and unobstructed. If no barrier exists, set 'has_barriers': false and create an issue with issue_type 'no_barrier_detected'.
5. Frame impacts as POSSIBILITIES ('may impede', 'could pose a hazard'), NEVER as absolute certainties of injury or harm.
6. Acknowledge the limits of a 2D photograph. List explicit UNKNOWNS (e.g., depth of puddle, subsurface stability, gradient percentage) and set 'verification_required': true if the issue cannot be fully determined from the angle or lighting.
7. Output valid JSON ONLY matching the exact schema requested. Do not include markdown code fences or conversational greetings.
"""

IMAGE_AUDIT_USER_PROMPT = """Analyze the attached street/pedestrian photograph for physical accessibility barriers.

Standard Issue Categories to consider:
- broken_footpath (cracked, fractured, or missing pavement)
- missing_ramp (abrupt curb without sloped transition)
- standing_water (waterlogging, submerged curb or puddle)
- encroachment_obstacle (parked vehicle, commercial hoardings, construction debris blocking path)
- damaged_walking_surface (loose pavers, uneven bricks, tactile paving dislodged)
- open_drainage_pothole (uncovered manhole, ditch, pothole)
- waste_overflow (garbage heap obstructing clearance)
- vegetation_overgrowth (low branches, bushes intruding into walking corridor)
- no_barrier_detected (clean, unobstructed, safe pedestrian route)

Provide your response as a strict JSON object with this exact structure:
{
  "audit_id": "AUDIT-<auto-generated>",
  "image_summary": "<Objective 1-2 sentence description of the street environment>",
  "has_barriers": <true if physical pedestrian obstacles are detected, false otherwise>,
  "issues": [
    {
      "issue_id": "ISSUE-001",
      "issue_type": "<standard_category_from_above>",
      "concise_description": "<Concise summary of the obstacle>",
      "visual_evidence": "<Direct, grounded visual observation from the photo, e.g. 'A 30cm wide cavity in the asphalt with exposed rubble'>",
      "affected_groups": ["wheelchair_users", "visually_impaired", "elderly", "strollers"],
      "potential_impact": "<Possible impact narrative explaining how travel might be obstructed or complicated>",
      "confidence_score": <number between 0.0 and 1.0 reflecting visual clarity>,
      "suggested_action": "<Concrete civic repair or maintenance recommendation>",
      "verification_required": <true if physical depth, gradient, or occlusion needs on-site inspection, false otherwise>,
      "unknowns": [
        "<Unknown factor 1, e.g., 'True depth of water puddle cannot be verified from 2D angle'>",
        "<Unknown factor 2, e.g., 'Exact ramp slope gradient cannot be measured without physical tools'>"
      ],
      "persona_impacts": {
        "wheelchair_users": "<Specific potential effect on wheelchair navigation or detours>",
        "visually_impaired": "<Specific potential effect on white cane users or tactile orientation>",
        "elderly": "<Specific potential effect on seniors or balance constraints>",
        "strollers": "<Specific potential effect on caregivers pushing strollers>"
      }
    }
  ],
  "overall_notes": "<Lighting conditions, perspective limitations, or general pedestrian context>",
  "verification_needed": <true if any issue flagged verification_required, false otherwise>
}
"""


def build_audit_prompt(custom_context: str = "") -> str:
    """Combines user prompt with optional citizen-provided context."""
    if custom_context and custom_context.strip():
        return f"{IMAGE_AUDIT_USER_PROMPT}\n\nAdditional Citizen-Provided Context for this location: {custom_context.strip()}"
    return IMAGE_AUDIT_USER_PROMPT
